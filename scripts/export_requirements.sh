#!/usr/bin/env bash

set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

uv lock

export_requirements() {
  local output_file="$1"
  shift

  {
    echo '# This file is autogenerated by uv. Do not edit it manually.'
    echo '# Add or update dependencies in pyproject.toml, then run scripts/export_requirements.sh.'
    # The hashed exports must stay closed under dependencies - pip rejects
    # anything pulled in but not pinned here, so never prune the resolution.
    uv export --locked --format requirements.txt --no-header \
      --no-annotate --no-emit-project "$@"
  } >"$output_file"
}

# Exports containing `torch` need the PyTorch index, as the lock pins the
# `+cu130` versions found only there. The config-test export stays on PyPI.
export_requirements requirements.txt --emit-index-url --no-default-groups
export_requirements requirements-dev.txt --emit-index-url --no-default-groups --group dev
export_requirements requirements-aimet.txt --emit-index-url --no-default-groups --extra aimet
export_requirements requirements-config.txt --only-group config-test
