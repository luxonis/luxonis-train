#!/usr/bin/env bash

set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
cd "$repo_root"

# Keep the lockfile and pip compatibility exports in sync with pyproject.toml.
uv lock

export_requirements() {
  local output_file="$1"
  shift

  local temporary_file
  temporary_file="$(mktemp "${output_file}.XXXXXX")"

  if ! {
    printf '%s\n' '# This file is autogenerated by uv. Do not edit it manually.'
    printf '%s\n' '# Add or update dependencies in pyproject.toml, then run scripts/export_requirements.sh.'
    uv export --locked --format requirements.txt --no-header --emit-index-url \
      --no-annotate --no-emit-project "$@"
  } >"$temporary_file"; then
    rm -f "$temporary_file"
    return 1
  fi

  mv "$temporary_file" "$output_file"
}

export_requirements requirements.txt --no-default-groups
export_requirements requirements-dev.txt --no-default-groups --group dev
export_requirements requirements-aimet.txt --no-default-groups --extra aimet
export_requirements requirements-config.txt --only-group config-test
