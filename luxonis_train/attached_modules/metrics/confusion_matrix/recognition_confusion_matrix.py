from torch import Tensor
from torchmetrics.classification import (
    BinaryConfusionMatrix,
    MulticlassConfusionMatrix,
)
from typing_extensions import override

from luxonis_train.attached_modules.metrics import BaseMetric
from luxonis_train.tasks import Tasks

from .utils import compute_mcc


class RecognitionConfusionMatrix(BaseMetric):
    r"""Confusion matrix for classification and semantic segmentation.

    Inputs:
        - ``predictions`` (``Tensor``): ``[B, n_classes, ...]`` logits
        - ``targets`` (``Tensor``): same shape, one-hot

    Outputs:
        - ``mcc`` (``Tensor``): scalar
        - ``confusion_matrix`` (``Tensor``): :math:`\left[n_{classes},
          n_{classes}\right]`

    Formula:
        Delegates confusion-matrix accumulation to torchmetrics and computes
        Matthews correlation coefficient from the resulting matrix.

    References:
        - Source: Wraps `torchmetrics
          <https://github.com/Lightning-AI/torchmetrics>`_ (Apache-2.0).
        - License: Apache-2.0 (this project)

    Notes:
        Selects binary or multiclass confusion matrix behavior from
        ``n_classes``.

    .. Generated by scripts/gen_component_docs.py. Do not edit.

    Example:
        Attached to a ``ClassificationHead`` in ``model.nodes``:

        .. code-block:: yaml

            - name: ClassificationHead
              inputs: [ResNet]
              metrics:
                - name: RecognitionConfusionMatrix

    Compatible with:
        - Nodes: ``BiSeNetHead``, ``ClassificationHead``,
          ``DDRNetSegmentationHead``, ``SegmentationHead``,
          ``TransformerClassificationHead``, ``TransformerSegmentationHead``

    """

    supported_tasks = [Tasks.CLASSIFICATION, Tasks.SEGMENTATION]

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        if self.n_classes == 1:
            self.metric = BinaryConfusionMatrix()
        else:
            self.metric = MulticlassConfusionMatrix(num_classes=self.n_classes)

    @override
    def update(self, predictions: Tensor, targets: Tensor) -> None:
        if self.n_classes > 1:
            self.metric.update(
                predictions.argmax(dim=1), targets.argmax(dim=1)
            )
        else:
            self.metric.update(predictions, targets)

    @override
    def compute(self) -> dict[str, Tensor]:
        cm = self.metric.compute()
        mcc = compute_mcc(cm.float())
        return {"mcc": mcc, "confusion_matrix": cm}

    @override
    def reset(self) -> None:
        self.metric.reset()
