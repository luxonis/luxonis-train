from loguru import logger
from torch import Tensor
from typing_extensions import override

from luxonis_train.tasks import Tasks
from luxonis_train.utils import keypoints_to_bboxes

from .detection_confusion_matrix import DetectionConfusionMatrix


class FomoConfusionMatrix(DetectionConfusionMatrix):
    r"""Confusion matrix for FOMO keypoint predictions.

    Inputs:
        - ``keypoints`` (``list[Tensor]``): :math:`\left[K_i, 1,
          4\right]` per image, ``(x, y, prob, class)``, pixels
        - ``target_boundingbox`` (``Tensor``): :math:`\left[N,
          6\right]`, ``[batch, class, x, y, w, h]``, ``xywh`` normalized

    Outputs:
        - ``mcc`` (``Tensor``): scalar
        - ``confusion_matrix`` (``Tensor``): :math:`\left[n_{classes} +
          1, n_{classes} + 1\right]`, last row and column are background

    Formula:
        Converts FOMO keypoints to zero-threshold boxes, then delegates matching
        and accumulation to ``DetectionConfusionMatrix``.

    References:
        - Source: This project.
        - License: Apache-2.0 (this project)

    Notes:
        Ignores user-provided nonzero IoU thresholds to preserve FOMO
        center-point semantics.

    .. Generated by scripts/gen_component_docs.py. Do not edit.

    Example:
        Attached to a ``FOMOHead`` in ``model.nodes``:

        .. code-block:: yaml

            - name: FOMOHead
              inputs: [EfficientRep]
              metrics:
                - name: FomoConfusionMatrix

    Compatible with:
        - Nodes: ``FOMOHead``

    """

    supported_tasks = [Tasks.FOMO]

    def __init__(self, iou_threshold: float | None = None, **kwargs):
        """Set the matching threshold.

        Args:
            iou_threshold (float): The IoU a predicted point needs, once
                it is turned into a box, to count as a match for a ground
                truth box.
            **kwargs (``Any``): Keyword arguments forwarded to
                `DetectionConfusionMatrix`.

        """
        if iou_threshold is not None and iou_threshold != 0.0:
            logger.warning(
                "The `iou_threshold` parameter is ignored for FomoConfusionMatrix and is hardcoded to 0. "
                "This is by design to align with FOMO's use case.",
            )
        super().__init__(iou_threshold=0.0, **kwargs)

    @override
    def update(
        self,
        keypoints: list[Tensor],
        target_boundingbox: Tensor,
    ) -> None:
        """Convert FOMO keypoints into bounding boxes before updating.

        Args:
            keypoints (``list[Tensor]``): Predicted FOMO keypoints.
            target_boundingbox (``Tensor``): Target bounding boxes.

        """
        pred_bboxes = keypoints_to_bboxes(
            keypoints,
            self.original_in_shape[1],
            self.original_in_shape[2],
        )

        super().update(pred_bboxes, target_boundingbox)
