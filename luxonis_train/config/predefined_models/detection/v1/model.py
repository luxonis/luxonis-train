"""The bounding box detection model."""

from luxonis_ml.typing import Params
from typing_extensions import override

from luxonis_train.config.predefined_models.base_predefined_model import (
    SimplePredefinedModel,
)


class DetectionModel(SimplePredefinedModel):
    """Bounding box detection, after `YOLOv6: A Single-Stage Object Detection
    Framework for Industrial Applications <https://arxiv.org/abs/2209.02976>`_.

    Throughput:
        Frames per second at 384x512.

        - ``light``: 50 on RVC2, 194 on RVC4
        - ``medium``: 25 on RVC2, 166 on RVC4
        - ``heavy``: 7 on RVC2, 120 on RVC4

    Accuracy:
        The figures come from models that trained on COCO train2017.
        The measurements use COCO val2017.

        - ``light``: 36.1 mAP
        - ``heavy``: 51.2 mAP

        The figures use a ``conf_thres`` of ``0.03`` and an
        ``iou_thres`` of ``0.65`` in ``head_params``. Published figures
        of other models use the same low confidence threshold and high
        IoU threshold.

    .. Generated by scripts/gen_component_docs.py. Do not edit.

    Example:
        The ``model`` section of a config:

        .. code-block:: yaml

            model:
              predefined_model:
                name: DetectionModel
                params:
                  variant: light

    Components:
        - Nodes: `EfficientRep` -> `RepPANNeck` -> `EfficientBBoxHead`
        - Losses: `AdaptiveDetectionLoss`
        - Metrics:

          - `ConfusionMatrix`
          - `MeanAveragePrecision`

        - Visualizers: `BBoxVisualizer`
        - Main metric: `MeanAveragePrecision`
        - Variants:

          - ``light``
          - ``medium``
          - ``heavy``

    """

    def __init__(self, **kwargs):
        super().__init__(
            **{
                "backbone": "EfficientRep",
                "neck": "RepPANNeck",
                "head": "EfficientBBoxHead",
                "loss": "AdaptiveDetectionLoss",
                "metrics": "MeanAveragePrecision",
                "confusion_matrix_available": True,
                "visualizer": "BBoxVisualizer",
            }
            | kwargs
        )

    @staticmethod
    @override
    def get_variants() -> tuple[str, dict[str, Params]]:
        """Get the default variant name and the available variants.

        The default is ``light``. Each variant sets ``backbone_variant``
        and ``neck_variant`` to one size:

        - ``light``: ``"n"``
        - ``medium``: ``"s"``
        - ``heavy``: ``"l"``

        Each variant also sets ``weights`` to ``"download"`` in
        ``backbone_params`` and ``neck_params``. Both nodes then
        download and load the COCO checkpoint of their variant. A
        ``backbone_params`` or ``neck_params`` given in the config
        replaces the whole dictionary of the variant. Set ``weights``
        in it again to keep the COCO checkpoint.

        Returns:
            ``tuple[str, dict[str, Params]]``: ``"light"`` and the three
            variants with their constructor arguments.

        Example:
            >>> default, variants = DetectionModel.get_variants()
            >>> default
            'light'
            >>> variants["medium"]["backbone_variant"]
            's'
            >>> variants["medium"]["neck_params"]
            {'weights': 'download'}

        """
        return "light", {
            "light": {
                "backbone_params": {"weights": "download"},
                "backbone_variant": "n",
                "neck_params": {"weights": "download"},
                "neck_variant": "n",
            },
            "medium": {
                "backbone_params": {"weights": "download"},
                "backbone_variant": "s",
                "neck_params": {"weights": "download"},
                "neck_variant": "s",
            },
            "heavy": {
                "backbone_params": {"weights": "download"},
                "backbone_variant": "l",
                "neck_params": {"weights": "download"},
                "neck_variant": "l",
            },
        }
