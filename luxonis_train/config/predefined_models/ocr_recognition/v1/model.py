"""The OCR text recognition model."""

from typing import Literal, TypeAlias

from loguru import logger
from luxonis_ml.typing import Params
from typing_extensions import override

from luxonis_train.config.predefined_models.base_predefined_model import (
    SimplePredefinedModel,
)

AlphabetName: TypeAlias = Literal[
    "english",
    "english_lowercase",
    "numeric",
    "alphanumeric",
    "alphanumeric_lowercase",
    "punctuation",
    "ascii",
]


class OCRRecognitionModel(SimplePredefinedModel):
    """Text recognition on a cropped image, after `PPOCRv4
    <https://github.com/PaddlePaddle/PaddleOCR>`_.

    The dataset needs the text of each image in the ``text`` metadata field:

    .. code-block:: python

        for path, label in zip(image_paths, labels):
            if label:
                yield {
                    "file": path,
                    "annotation": {"metadata": {"text": label}},
                }

    Set ``alphabet`` to the characters to recognize, either as a list or as
    one of the named alphabets, and ``max_text_len`` to the longest string
    to expect.

    Throughput:
        Frames per second at 48x320.

        - ``light``: 50 on RVC2, 300 on RVC4

    .. Generated by scripts/gen_component_docs.py. Do not edit.

    Example:
        The ``model`` section of a config:

        .. code-block:: yaml

            model:
              predefined_model:
                name: OCRRecognitionModel
                params:
                  variant: light

    Components:
        - Nodes: `PPLCNetV3` -> `SVTRNeck` -> `OCRCTCHead`
        - Losses: `CTCLoss`
        - Metrics: `OCRAccuracy`
        - Visualizers: `OCRVisualizer`
        - Main metric: `OCRAccuracy`
        - Variants: ``light``

    """

    def __init__(
        self,
        alphabet: list[str] | AlphabetName = "english",
        max_text_len: int = 40,
        ignore_unknown: bool = True,
        **kwargs,
    ):
        """Initialize the model with its default components.

        Args:
            alphabet (``list[str] | AlphabetName``): The characters that
                the head predicts. A name selects a predefined alphabet
                and logs an info message:

                - ``"english"``: ``a`` to ``z`` and ``A`` to ``Z``;
                - ``"english_lowercase"``: ``a`` to ``z``;
                - ``"numeric"``: ``0`` to ``9``;
                - ``"alphanumeric"``: ``"english"`` and ``"numeric"``;
                - ``"alphanumeric_lowercase"``: ``"english_lowercase"``
                  and ``"numeric"``;
                - ``"punctuation"``: the space and the ASCII punctuation
                  characters;
                - ``"ascii"``: the printable ASCII characters, codes
                  ``32`` to ``126``.

                The model passes a list on without a change. It does
                not read the value when ``head_params`` holds
                ``alphabet``.
            max_text_len (int): The number of sequence steps of the
                backbone output, and so the longest text the model can
                predict.
            ignore_unknown (bool): Whether the head drops a label
                character that is not in the alphabet. With ``False``,
                the head maps it to an extra ``"<UNK>"`` class.
            **kwargs (``Any``): Keyword arguments for
                `SimplePredefinedModel.__init__`.

        Raises:
            ValueError: When ``alphabet`` is a string that names no
                predefined alphabet, and ``head_params`` holds no
                ``alphabet``.

        Example:
            >>> model = OCRRecognitionModel(
            ...     alphabet=["a", "b"], max_text_len=8
            ... )
            >>> backbone, _, head = model.nodes
            >>> backbone.params
            {'max_text_len': 8}
            >>> head.params
            {'alphabet': ['a', 'b'], 'ignore_unknown': True}

        """
        super().__init__(
            **{
                "backbone": "PPLCNetV3",
                "neck": "SVTRNeck",
                "head": "OCRCTCHead",
                "loss": "CTCLoss",
                "metrics": "OCRAccuracy",
                "confusion_matrix_available": False,
                "visualizer": "OCRVisualizer",
            }
            | kwargs
        )
        if "max_text_len" not in self._backbone_params:
            self._backbone_params["max_text_len"] = max_text_len
        if "alphabet" not in self._head_params:
            self._head_params["alphabet"] = self._generate_alphabet(alphabet)
        if "ignore_unknown" not in self._head_params:
            self._head_params["ignore_unknown"] = ignore_unknown

    @staticmethod
    @override
    def get_variants() -> tuple[str, dict[str, Params]]:
        """Get the default variant name and the available variants.

        The model has one variant, ``light``. It sets
        ``backbone_variant`` to ``"rec-light"``, the recognition variant
        of `PPLCNetV3`. The variant sets no ``weights``, so no node
        loads a checkpoint.

        Returns:
            ``tuple[str, dict[str, Params]]``: ``"light"`` and the single
            variant with its constructor arguments.

        Example:
            >>> OCRRecognitionModel.get_variants()
            ('light', {'light': {'backbone_variant': 'rec-light'}})

        """
        return "light", {
            "light": {
                "backbone_variant": "rec-light",
            }
        }

    @staticmethod
    def _generate_alphabet(alphabet: list[str] | AlphabetName) -> list[str]:
        alphabets = {
            "english": "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ",
            "english_lowercase": "abcdefghijklmnopqrstuvwxyz",
            "numeric": "0123456789",
            "alphanumeric": "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789",
            "alphanumeric_lowercase": "abcdefghijklmnopqrstuvwxyz0123456789",
            "punctuation": " !\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~",
            "ascii": "".join(chr(i) for i in range(32, 127)),
        }

        if isinstance(alphabet, str):
            if alphabet not in alphabets:
                raise ValueError(
                    f"Invalid alphabet name '{alphabet}'. "
                    f"Available options are: {list(alphabets.keys())}. "
                    f"Alternatively, you can provide a custom alphabet as a list of characters."
                )
            logger.info(f"Using predefined alphabet '{alphabet}'.")
            alphabet = list(alphabets[alphabet])

        return alphabet
