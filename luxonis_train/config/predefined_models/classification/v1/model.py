"""The classification model."""

from luxonis_ml.typing import Params
from typing_extensions import override

from luxonis_train.config.predefined_models.base_predefined_model import (
    SimplePredefinedModel,
)


class ClassificationModel(SimplePredefinedModel):
    """Single-label or multi-label classification.

    Throughput:
        Frames per second at 384x512.

        - ``light``: 46 on RVC2, 176 on RVC4
        - ``heavy``: 5 on RVC2, 134 on RVC4

    Notes:
        Set ``task`` to ``multilabel`` when an image can carry more than one
        class. The metrics read the same setting.

    .. Generated by scripts/gen_component_docs.py. Do not edit.

    Example:
        The ``model`` section of a config:

        .. code-block:: yaml

            model:
              predefined_model:
                name: ClassificationModel
                params:
                  variant: light

    Components:
        - Nodes: ``ResNet`` -> ``ClassificationHead``
        - Losses: ``CrossEntropyLoss``
        - Metrics: ``Accuracy``, ``ConfusionMatrix``, ``F1Score``, ``Recall``
        - Visualizers: ``ClassificationVisualizer``
        - Main metric: ``F1Score``
        - Variants: ``light``, ``heavy``

    """

    def __init__(self, **kwargs):
        super().__init__(
            **{
                "backbone": "ResNet",
                "head": "ClassificationHead",
                "loss": "CrossEntropyLoss",
                "metrics": ["F1Score", "Accuracy", "Recall"],
                "confusion_matrix_available": True,
                "main_metric": "F1Score",
                "visualizer": "ClassificationVisualizer",
            }
            | kwargs
        )

    @staticmethod
    @override
    def get_variants() -> tuple[str, dict[str, Params]]:
        return "light", {
            "light": {
                "backbone": "ResNet",
                "backbone_variant": "18",
            },
            "heavy": {
                "backbone": "ResNet",
                "backbone_variant": "50",
            },
        }
